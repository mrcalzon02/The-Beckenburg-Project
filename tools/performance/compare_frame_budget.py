#!/usr/bin/env python3
"""Compare two Beckenburg frame-budget JSON reports without hiding regressions.

Diagnostic only. Input must be generated by frame_budget_report.py, using the
same display-frame sampling method, hardware, viewport, and gameplay route.
This compares distributions, not paired frames or statistical significance.
"""
import argparse
import json
import math
from pathlib import Path

METRICS = ('p50_ms', 'p95_ms', 'p99_ms', 'max_ms', 'over_100_ms')


def load(path):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if data.get('schema') != 2 or data.get('unit') != 'ms' or data.get('percentile') != 'nearest-rank':
        raise ValueError(f'{path}: unsupported report schema, units or percentile method')
    if data.get('per_trial'):
        raise ValueError(f'{path}: use pooled reports for comparisons; review per-trial reports separately')
    groups = {}
    for row in data.get('groups', []):
        key = (row.get('mode'), row.get('phase'))
        if not all(key) or key in groups:
            raise ValueError(f'{path}: missing or duplicate mode/phase')
        if type(row.get('intervals')) is not int or row['intervals'] < 1:
            raise ValueError(f'{path}: invalid sample count for {key}')
        for field in METRICS:
            value = row.get(field)
            if type(value) not in (int, float) or not math.isfinite(value) or value < 0:
                raise ValueError(f'{path}: invalid {field} for {key}')
        groups[key] = row
    if not groups:
        raise ValueError(f'{path}: no groups')
    return groups


def compare(baseline, candidate):
    before, after = load(baseline), load(candidate)
    if before.keys() != after.keys():
        missing = sorted(before.keys() - after.keys())
        added = sorted(after.keys() - before.keys())
        raise ValueError(f'mismatched groups; missing={missing}, added={added}')
    rows = []
    for mode, phase in sorted(before):
        a, b = before[(mode, phase)], after[(mode, phase)]
        row = {'mode': mode, 'phase': phase, 'baseline_n': a['intervals'], 'candidate_n': b['intervals']}
        for metric in METRICS:
            row[f'baseline_{metric}'] = a[metric]
            row[f'candidate_{metric}'] = b[metric]
            row[f'delta_{metric}'] = round(b[metric] - a[metric], 3)
        rows.append(row)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('baseline', help='baseline JSON produced by frame_budget_report.py')
    parser.add_argument('candidate', help='candidate JSON produced by frame_budget_report.py')
    parser.add_argument('--json', help='write machine-readable comparison')
    args = parser.parse_args()
    try:
        rows = compare(args.baseline, args.candidate)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        parser.error(str(exc))
    print('MODE | PHASE | SAMPLES before/after | p95 change ms | p99 change ms | >100 change')
    for row in rows:
        print(f"{row['mode']} | {row['phase']} | {row['baseline_n']}/{row['candidate_n']} | "
              f"{row['delta_p95_ms']:+.3f} | {row['delta_p99_ms']:+.3f} | {row['delta_over_100_ms']:+.0f}")
    print('Diagnostic only: compare matching hardware, route, viewport, and sampling; negative deltas are improvements.')
    if args.json:
        Path(args.json).write_text(json.dumps({'schema': 1, 'release_gate': False, 'comparisons': rows}, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
