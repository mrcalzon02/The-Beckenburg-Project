"""Derive the native Castle cellar and flight dimensions from the approved rough."""
from pathlib import Path
import argparse, importlib.util, json
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('castle_rough',ROOT/'tools/build_map_rebuild_roughs.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
d=m.apply_search_envelope(m.castle());m.validate(d)
rooms=[r for r in d['zones'] if r['y']<0]
ids={r['id'] for r in rooms}
links=[l for l in d['links'] if l['kind']=='level' and l['a'] in ids and l['b'] in ids]
flight=next(l for l in d['links'] if l['kind']=='stairs' and l['a']=='cellar-stair')
start,end=flight['points'];assert start[0]==end[0] and start[1]==-3 and end[1]==0
lines={}
for r in rooms:
 x0,z0,x1,z1=r['bounds']
 for h,p,a,b in [(True,z0,x0,x1),(True,z1,x0,x1),(False,x0,z0,z1),(False,x1,z0,z1)]:lines.setdefault((h,p),[]).append((a,b))
walls=[]
def wall(h,p,a,b,lo=-3,hi=0,portal=None,width=0):
 if b-a>1e-8:walls.append((a if h else p,p if h else a,b if h else p,p if h else b,lo,hi,portal,width))
for (h,p),spans in sorted(lines.items()):
 merged=[]
 for a,b in sorted(spans):
  if merged and a<=merged[-1][1]+1e-8:merged[-1]=(merged[-1][0],max(b,merged[-1][1]))
  else:merged.append((a,b))
 for a,b in merged:
  cuts=[]
  for l in links:
   x,y,z=l['threshold'];q=z if h else x;t=x if h else z
   if abs(q-p)<1e-8 and a<t<b:cuts.append((t,l['width']))
  at=a
  for mid,w in sorted(cuts):
   left,right=mid-w/2,mid+w/2;assert at<=left<right<=b
   wall(h,p,at,left);wall(h,p,left,right,-.6,0);wall(h,p,left,right,-3,-3,mid,w);at=right
  wall(h,p,at,b)
def n(x):return str(float(x))
room_code=',\n        '.join('new CastleRooms.Room('+json.dumps(r['id'])+','+json.dumps(r['name'])+','+','.join(n(x) for x in r['bounds'])+',-3,0,false,MaterialAtlas.STONE)' for r in rooms)
wall_code=',\n        '.join('new CastleHubArchitecturalPlan.Wall('+','.join(n(x) for x in w[:6])+',MaterialAtlas.STONE,'+('Double.NaN' if w[6] is None else n(w[6]))+','+n(w[7])+')' for w in walls)
out='''package org.beckenburg;
import java.util.List;
/** GENERATED by tools/build_castle_cellar.py; native/editor/runtime construction authority. */
public final class CastleCellarLayout {
    private CastleCellarLayout(){}
    public static final double FLIGHT_X=FX,LOW_Z=LZ,HIGH_Z=HZ,WIDTH=WW;
    public static final int RISERS=NN;
    public static final List<CastleRooms.Room> ROOMS=List.of(
        ROOMS_CODE);
    public static final List<CastleHubArchitecturalPlan.Wall> WALLS=List.of(
        WALLS_CODE);
}
'''.replace('FX',n(start[0])).replace('LZ',n(start[2])).replace('HZ',n(end[2])).replace('WW',n(flight['width'])).replace('NN',str(flight['risers'])).replace('ROOMS_CODE',room_code).replace('WALLS_CODE',wall_code)
p=ROOT/'src/main/java/org/beckenburg/CastleCellarLayout.java';raw=out.encode()
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');a=args.parse_args()
if a.check:assert p.read_bytes()==raw,'Stale native cellar authority'
else:p.write_bytes(raw)
print(f'PASS native Castle cellar authority: {len(rooms)} rooms, {len(walls)} wall/lintel/portal records, {flight["risers"]} risers')
