package org.beckenburg;

import java.util.Locale;
import java.util.Objects;

/**
 * Host-side environmental measurement model for the expanded evidence system.
 * Deterministic within an observation window; sampling must never roll a new
 * supernatural event, authorize evidence, or reveal the hidden ghost identity.
 * Live solo/LAN scans use these readings. No sample certifies ghost identity.
 */
public final class EvidenceSignals {
    private EvidenceSignals() { }
    public enum Season { WINTER, SPRING, SUMMER, AUTUMN }
    /** Network-stable Beckenburg weather names backed by the shared PSX weather module.
     * WIND and HEATWAVE remain decode-compatible legacy aliases but are hidden from new contracts.
     */
    public enum Weather {
        CLEAR(dev.mrcalzon.weather.WeatherType.CLEAR),
        OVERCAST(dev.mrcalzon.weather.WeatherType.OVERCAST),
        DRIZZLE(dev.mrcalzon.weather.WeatherType.DRIZZLE),
        RAIN(dev.mrcalzon.weather.WeatherType.RAIN),
        HEAVY_RAIN(dev.mrcalzon.weather.WeatherType.HEAVY_RAIN),
        THUNDERSTORM(dev.mrcalzon.weather.WeatherType.THUNDERSTORM),
        FOG(dev.mrcalzon.weather.WeatherType.FOG),
        DENSE_FOG(dev.mrcalzon.weather.WeatherType.DENSE_FOG),
        SNOW(dev.mrcalzon.weather.WeatherType.SNOW),
        BLIZZARD(dev.mrcalzon.weather.WeatherType.BLIZZARD),
        SLEET(dev.mrcalzon.weather.WeatherType.SLEET),
        HAIL(dev.mrcalzon.weather.WeatherType.HAIL),
        DUST_STORM(dev.mrcalzon.weather.WeatherType.DUST_STORM),
        ASHFALL(dev.mrcalzon.weather.WeatherType.ASHFALL),
        MIASMA(dev.mrcalzon.weather.WeatherType.MIASMA),
        /** Legacy save/network compatibility; not offered in the weather picker. */
        HEATWAVE(dev.mrcalzon.weather.WeatherType.CLEAR),
        /** Legacy save/network compatibility; new contracts use OVERCAST/precipitation profiles. */
        WIND(dev.mrcalzon.weather.WeatherType.OVERCAST);

        private final dev.mrcalzon.weather.WeatherType moduleType;
        Weather(dev.mrcalzon.weather.WeatherType moduleType){this.moduleType=moduleType;}
        public dev.mrcalzon.weather.WeatherType moduleType(){return moduleType;}
        public boolean selectable(){return this!=HEATWAVE&&this!=WIND;}
        public static Weather[] selectableValues(){
            return new Weather[]{CLEAR,OVERCAST,DRIZZLE,RAIN,HEAVY_RAIN,THUNDERSTORM,
                FOG,DENSE_FOG,SNOW,BLIZZARD,SLEET,HAIL,DUST_STORM,ASHFALL,MIASMA};
        }
    }
    public enum Polarity { NONE, COLD, HOT }
    public enum Unit { CELSIUS, FAHRENHEIT }
    public record Location(Season season, Weather weather, int hour, int room,
                           boolean indoors, boolean heatingOn) {
        public Location {
            Objects.requireNonNull(season); Objects.requireNonNull(weather);
            if(hour<0||hour>23||room<0)throw new IllegalArgumentException("invalid climate context");
        }
    }
    public record Temperature(double celsius, double ambientCelsius,
                              boolean paranormalExtreme) {
        public Temperature {
            if(!Double.isFinite(celsius)||!Double.isFinite(ambientCelsius))
                throw new IllegalArgumentException("non-finite temperature");
        }
        public double display(Unit unit){
            Objects.requireNonNull(unit);
            return unit==Unit.CELSIUS?celsius:cToF(celsius);
        }
        public String displayText(Unit unit){
            return String.format(Locale.ROOT,"%.1f%s",display(unit),
                unit==Unit.CELSIUS?"°C":"°F");
        }
    }
    /** A reading is never a certification. highEvent only describes the value
     * range generated by a genuine local event, NOT a journal mark or deduction.
     */
    public record Electromagnetic(int level, boolean highEvent, boolean suppressed) {
        public Electromagnetic {
            if(level<0||level>10||(level==0)!=suppressed
                    ||highEvent&&(level<8||suppressed))
                throw new IllegalArgumentException("invalid EMF");
        }
        public Electromagnetic(int level,boolean highEvent){
            this(level,highEvent,false);
        }
    }
    public static double cToF(double c){return c*9.0/5.0+32.0;}
    public static double fToC(double f){return (f-32.0)*5.0/9.0;}
    private static int hash(long seed,int room,int window){
        long x=seed+0x9e3779b97f4a7c15L*(room+1L)
            +0xc2b2ae3d27d4eb4fL*(window+1L);
        x^=x>>>30;x*=0xbf58476d1ce4e5b9L;
        x^=x>>>27;x*=0x94d049bb133111ebL;x^=x>>>31;
        return (int)(x&0x7fffffff);
    }
    /** Ordinary environmental/weak ghost events fluctuate 2..7; strong
     * local events of non-suppressing ghosts can produce 8..10. Suppression
     * may read 0. Nothing is auto-ticked as evidence.
     */
    public static Electromagnetic emf(long seed,int tick,int room,
                                    int eventRoom,int eventStrength){
        return emf(seed,tick,room,eventRoom,eventStrength,false);
    }
    public static Electromagnetic emf(long seed,int tick,int room,
                                    int eventRoom,int eventStrength,boolean suppression){
        return emf(seed,tick,room,eventRoom,eventStrength,suppression,Weather.CLEAR,1);
    }
    /** Weather changes *ordinary* field noise but cannot create false ghost-event EMF 8-10.
     * Snow suppresses background activity; electrical storms elevate it to 5-7.
     */
    public static Electromagnetic emf(long seed,int tick,int room,
                int eventRoom,int eventStrength,boolean suppression,Weather weather,int intensity){
        return emf(seed,tick,room,eventRoom,eventStrength,
            suppression?GhostEvidenceProfile.EmfBand.NONE:GhostEvidenceProfile.EmfBand.HIGH,
            weather,intensity);
    }
    /** The EMF family has three *species* outcomes: 8–10, 2–7 or 0.
     * Weather may alter ordinary 2–7 background, never the ghost's signature.
     */
    public static Electromagnetic emf(long seed,int tick,int room,
                int eventRoom,int eventStrength,GhostEvidenceProfile.EmfBand band,
                Weather weather,int intensity){
        Objects.requireNonNull(band);
        Objects.requireNonNull(weather);
        if(intensity<1||intensity>3)throw new IllegalArgumentException("EMF weather intensity");
        if(tick<0||room<0||eventStrength<0||eventStrength>10)
            throw new IllegalArgumentException("invalid EMF context");
        int ambient=2+hash(seed,room,tick/5)%3;
        if(weather==Weather.THUNDERSTORM)ambient=Math.min(7,ambient+1+intensity);
        else if(weather==Weather.HAIL)ambient=Math.min(7,ambient+1+intensity/2);
        else if(weather==Weather.HEAVY_RAIN||weather==Weather.SLEET)
            ambient=Math.min(7,ambient+Math.max(1,intensity));
        else if(weather==Weather.RAIN||weather==Weather.DRIZZLE)
            ambient=Math.min(7,ambient+intensity/2);
        else if(weather==Weather.SNOW||weather==Weather.BLIZZARD)
            ambient=Math.max(2,ambient-intensity);
        else if(weather==Weather.DUST_STORM||weather==Weather.ASHFALL)
            ambient=Math.min(7,ambient+1);
        else if(weather==Weather.WIND)ambient=Math.min(7,ambient+1);
        boolean local=room==eventRoom&&eventStrength>0;
        boolean strong=local&&eventStrength>=8;
        // Ghost event signatures override weather noise only for confirmed host events.
        if(local&&band==GhostEvidenceProfile.EmfBand.NONE)
            return new Electromagnetic(0,false,true);
        if(strong&&band==GhostEvidenceProfile.EmfBand.HIGH)
            return new Electromagnetic(8+hash(seed^0x5317L,room,tick/5)%3,true,false);
        if(strong&&band==GhostEvidenceProfile.EmfBand.LOW_MID)
            return new Electromagnetic(4+hash(seed^0x5317L,room,tick/5)%4,false,false);
        int level=Math.min(7,ambient+(local?Math.min(3,(eventStrength+1)/2):0));
        return new Electromagnetic(level,false,false);
    }
    /** Seasonal/weather/time baseline, applied to both outside and indoor air. */
    public static double ambientC(Location place){return ambientC(place,1);}
    public static double ambientC(Location place,int intensity){
        Objects.requireNonNull(place);
        if(intensity<1||intensity>3)throw new IllegalArgumentException("thermal weather intensity");
        double outside=switch(place.season()){
            case WINTER->-8.0;case SPRING->10.0;case SUMMER->24.0;case AUTUMN->11.0;
        };
        outside+=switch(place.weather()){
            case CLEAR->0.0;
            case OVERCAST->-0.5;
            case DRIZZLE->-1.0-.5*intensity;
            case RAIN->-2.0-intensity;
            case HEAVY_RAIN->-3.0-1.5*intensity;
            case THUNDERSTORM->-2.0-1.5*intensity;
            case FOG->-1.0-.7*intensity;
            case DENSE_FOG->-1.5-intensity;
            case SNOW->-4.0-2.0*intensity;
            case BLIZZARD->-7.0-2.5*intensity;
            case SLEET->-4.0-1.5*intensity;
            case HAIL->-3.0-intensity;
            case DUST_STORM->1.0+intensity;
            case ASHFALL->-2.0-intensity;
            case MIASMA->-1.0;
            case HEATWAVE->6.0+3.0*intensity;
            case WIND->-1.0-intensity;
        };
        outside+=place.hour()>=11&&place.hour()<=17?3.0:
                 place.hour()<=5||place.hour()>=21?-4.0:0.0;
        if(!place.indoors())return outside;
        double interior=place.heatingOn()?outside+(20.0-outside)*0.8:
                          outside+(19.0-outside)*0.22;
        // Room-level offsets: insulation, draft and adjoining heat sources.
        return interior+(hash(0x5eeDL,place.room(),0)%7-3)*0.55;
    }
    /**
     * Temperature changes over time rather than being a static room-type code.
     * Cold/hot supernatural rooms hold an extreme relative to their baseline.
     * Ordinary winter freezing by itself is not paranormal evidence.
     */
    public static Temperature temperature(long seed,int tick,Location place,
            Polarity polarity,boolean hauntedRoom,int eventStrength){
        return temperature(seed,tick,place,polarity,hauntedRoom,eventStrength,1);
    }
    public static Temperature temperature(long seed,int tick,Location place,
            Polarity polarity,boolean hauntedRoom,int eventStrength,int intensity){
        if(tick<0||eventStrength<0||eventStrength>10)
            throw new IllegalArgumentException("invalid thermal context");
        Objects.requireNonNull(polarity);
        double ambient=ambientC(place,intensity);
        double drift=(hash(seed,place.room(),tick/20)%27-13)*0.12;
        double actual=ambient+drift;
        if(hauntedRoom){
            if(polarity==Polarity.COLD)
                actual-=4.0+eventStrength*2.1;
            else if(polarity==Polarity.HOT)
                actual+=4.0+eventStrength*2.0;
            else {
                // Thermal-neutral ghosts still warm/cool the room naturally during
                // activities; NONE merely means no species-linked extreme.
                double direction=hash(seed^0x74A7L,place.room(),tick/35)%2==0?1:-1;
                actual+=direction*(eventStrength*0.30);
            }
        }
        boolean extreme=(polarity==Polarity.COLD&&actual<0.0
                        ||polarity==Polarity.HOT&&cToF(actual)>=90.0)
                        &&hauntedRoom&&Math.abs(actual-ambient)>=8.0;
        return new Temperature(actual,ambient,extreme);
    }
}
